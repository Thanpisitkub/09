#!/usr/bin/env python3
"""Uploads assets/icons/*.png to Roblox as Image assets (Open Cloud) and writes src/shared/IconIds.luau.

- Only new or changed icons are uploaded (cache: assets/icon_ids.json, keyed by file hash),
  because Roblox has no delete for uploaded assets.
- Needs env ROBLOX_API_KEY (with the Assets API: read + write) and ROBLOX_USER_ID (or ROBLOX_GROUP_ID).
  If either is missing the script only rebuilds IconIds.luau from the cache and exits 0, so the game
  still publishes (the UI falls back to emoji for icons that have no id yet).
- Uses the standard library only.
"""
import hashlib, json, os, sys, time, uuid, urllib.request, urllib.error
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ICONS = ROOT / "assets" / "icons"
CACHE = ROOT / "assets" / "icon_ids.json"
LUAU = ROOT / "src" / "shared" / "IconIds.luau"
ASSETS_URL = "https://apis.roblox.com/assets/v1/assets"
OPERATION_URL = "https://apis.roblox.com/assets/v1/operations/{op}"


def sha(p):
    return hashlib.sha1(p.read_bytes()).hexdigest()[:16]


def multipart(request: dict, filename: str, data: bytes):
    boundary = "----tffa" + uuid.uuid4().hex
    parts = [
        f'--{boundary}\r\nContent-Disposition: form-data; name="request"\r\nContent-Type: application/json\r\n\r\n'.encode()
        + json.dumps(request).encode() + b"\r\n",
        f'--{boundary}\r\nContent-Disposition: form-data; name="fileContent"; filename="{filename}"\r\nContent-Type: image/png\r\n\r\n'.encode()
        + data + b"\r\n",
        f"--{boundary}--\r\n".encode(),
    ]
    return boundary, b"".join(parts)


def call(req):
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            return r.status, json.loads(r.read() or b"{}")
    except urllib.error.HTTPError as e:
        return e.code, {"error": e.read().decode("utf-8", "replace")[:300]}
    except Exception as e:  # network hiccup: report, keep going
        return 0, {"error": str(e)}


def upload(path, key, creator):
    request = {"assetType": "Image", "displayName": f"TFFA_{path.stem}",
               "description": "Throw Food For Animals UI icon", "creationContext": {"creator": creator}}
    boundary, body = multipart(request, path.name, path.read_bytes())
    req = urllib.request.Request(ASSETS_URL, data=body, method="POST", headers={
        "x-api-key": key, "Content-Type": f"multipart/form-data; boundary={boundary}"})
    status, resp = call(req)
    if status >= 300 or status == 0:
        return None, f"upload refused {status}: {resp.get('error')}"
    op = resp.get("operationId") or str(resp.get("path", "")).rsplit("/", 1)[-1]
    for _ in range(60):
        time.sleep(2)
        status, body = call(urllib.request.Request(OPERATION_URL.format(op=op), headers={"x-api-key": key}))
        if status >= 300 or status == 0:
            return None, f"poll failed {status}: {body.get('error')}"
        if body.get("done"):
            aid = (body.get("response") or {}).get("assetId")
            return (str(aid), None) if aid else (None, f"no assetId: {body}")
    return None, "timed out waiting for the upload to finish"


def write_luau(cache):
    lines = ["-- GENERATED by tools/upload_icons.py. Do not edit by hand.", "return {"]
    for name in sorted(cache):
        lines.append(f'\t{name} = {int(cache[name]["id"])},')
    lines.append("}")
    LUAU.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    cache = json.loads(CACHE.read_text()) if CACHE.exists() else {}
    key = os.environ.get("ROBLOX_API_KEY", "").strip()
    uid, gid = os.environ.get("ROBLOX_USER_ID", "").strip(), os.environ.get("ROBLOX_GROUP_ID", "").strip()
    creator = {"groupId": gid} if gid else {"userId": uid} if uid else None
    icons = sorted(ICONS.glob("*.png"))
    todo = [p for p in icons if cache.get(p.stem, {}).get("sha") != sha(p)]
    print(f"{len(icons)} icons, {len(todo)} to upload, {len(icons) - len(todo)} already uploaded")

    if todo and (not key or not creator):
        print("ROBLOX_API_KEY / ROBLOX_USER_ID not set: skipping upload (UI will use emoji for these icons)")
        todo = []
    failed = 0
    for i, p in enumerate(todo, 1):
        aid, err = upload(p, key, creator)
        if err:
            failed += 1
            print(f"[{i}/{len(todo)}] {p.stem}: FAILED {err}")
            if failed >= 3 and not any(True for _ in cache):
                print("several uploads failed in a row: check the key's Assets permission and the user id")
                break
            continue
        cache[p.stem] = {"id": aid, "sha": sha(p)}
        CACHE.write_text(json.dumps(cache, indent=1, sort_keys=True))
        print(f"[{i}/{len(todo)}] {p.stem} -> {aid}")
    write_luau(cache)
    print(f"IconIds.luau written with {len(cache)} icons")
    return 0


if __name__ == "__main__":
    sys.exit(main())
